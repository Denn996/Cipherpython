num1 = float(input("Enter number one: "))
num2 = float(input("Enter number two: "))


result1 = num1 + num2
print(f"The sum of {num1} and {num2} is {result1}")

result2 = num1 * num2
print(f"The product of {num1} and {num2} is {result2}")

result3 = num1 / num2
print(f"The division of {num1} and {num2} is {result3}")